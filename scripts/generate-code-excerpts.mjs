import { readFile, writeFile } from 'node:fs/promises';

const sourcePath = new URL('../docs/code/teaching_transformer.py', import.meta.url);
const outputPath = new URL('../src/data/generatedCodeBlocks.js', import.meta.url);
const source = await readFile(sourcePath, 'utf8');
const sourceLines = source.split(/\r?\n/);

const regions = [
  ['imports', null, 'Imports & Setup'],
  ['data-prep', 'data-prep', 'Data Preparation'],
  ['feedforward', 'feedforward', 'FeedForward Network'],
  ['attention', 'attention', 'Multi-Head Attention'],
  ['block', 'block', 'Transformer Block'],
  ['model', 'model', 'GPT Model'],
  ['generation', 'generation', 'Text Generation'],
  ['training', 'training', 'Training Loop'],
];

const blocks = regions.map(([id, section, title]) => {
  const start = sourceLines.indexOf(`# region ${id}`);
  const end = sourceLines.indexOf(`# endregion ${id}`);
  if (start < 0 || end <= start) {
    throw new Error(`Missing or malformed source region: ${id}`);
  }
  return {
    id,
    section,
    title,
    sourcePath: 'docs/code/teaching_transformer.py',
    startLine: start + 2,
    endLine: end,
    expressionId: `${id}.operation`,
    code: sourceLines.slice(start + 1, end).join('\n').trimEnd(),
  };
});

const generated = `// Generated by scripts/generate-code-excerpts.mjs from docs/code/teaching_transformer.py.\nexport const codeBlocks = ${JSON.stringify(blocks, null, 2)};\n`;
await writeFile(outputPath, generated);
console.log(`Generated ${blocks.length} code excerpts from ${sourcePath.pathname}`);
